def calculer_S_f_1_c(
    b,
    r,
    A,
    Q
    ):

    
    S_f = (
        r ** 2
    ) * (
        (b + 2 * A / b) ** (4 / 3)
    ) * (
        Q * abs(Q)
    ) / (
        A ** (10 / 3)
    )

    
    return S_f
