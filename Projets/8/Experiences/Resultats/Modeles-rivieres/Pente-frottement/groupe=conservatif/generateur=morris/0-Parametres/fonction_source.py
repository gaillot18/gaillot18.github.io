def calculer_S_f_1_p(
    b,
    r,
    h,
    u
    ):

    
    S_f = (
        r ** 2 * (b + 2 * h) ** (4 / 3) * u * abs(u)
    ) / (
        b ** (4 / 3) * h ** (4 / 3)
    )

    
    return S_f
